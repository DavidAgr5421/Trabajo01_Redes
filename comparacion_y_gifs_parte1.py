def algoritmo_evolutivo_gif(
    f_obj, dimension=2, lb=-5.0, ub=5.0,
    n_pop=50, max_generaciones=100,
    frac_elitismo=0.15, frac_mutacion=0.20,
    frac_cruzamiento=0.65, semilla=None
):
    if semilla is not None:
        np.random.seed(semilla)

    lim_inf = np.full(dimension, lb) if np.isscalar(lb) else np.asarray(lb)
    lim_sup = np.full(dimension, ub) if np.isscalar(ub) else np.asarray(ub)

    contador = {"evals": 0}

    # Se reutilizan los operadores originales de tus compañeros
    pob = algoritmo_evolutivo.poblacion_inicial(
        n_pop, dimension, lim_inf, lim_sup
    )
    fitness = algoritmo_evolutivo.evaluar_poblacion(
        pob, f_obj, contador
    )

    orden = np.argsort(fitness)
    pob = pob[orden]
    fitness = fitness[orden]

    mejor_x = pob[0].copy()
    mejor_f = fitness[0]

    historial_mejor_f = [mejor_f]
    historial_mejor_x = [mejor_x.copy()]
    historial_poblacion = [pob.copy()]

    n_elite = int(np.round(n_pop * frac_elitismo))
    n_mutantes = int(np.round(n_pop * frac_mutacion))
    n_hijos = n_pop - n_elite - n_mutantes

    if n_hijos < 0:
        n_hijos = 0
        n_mutantes = n_pop - n_elite

    for gen in range(1, max_generaciones + 1):
        elite = algoritmo_evolutivo.elitismo(pob, n_elite)

        hijos = algoritmo_evolutivo.cruzamiento(
            pob, n_hijos, dimension
        )
        mutantes = algoritmo_evolutivo.mutacion(
            pob, n_mutantes, lim_inf, lim_sup
        )

        nueva_pob = np.vstack([elite, hijos, mutantes])[:n_pop]

        fitness_nuevos = np.zeros(n_pop)
        fitness_nuevos[:n_elite] = fitness[:n_elite]

        for k in range(n_elite, n_pop):
            fitness_nuevos[k] = f_obj(nueva_pob[k])
            contador["evals"] += 1

        orden = np.argsort(fitness_nuevos)
        pob = nueva_pob[orden]
        fitness = fitness_nuevos[orden]

        if fitness[0] < mejor_f:
            mejor_f = fitness[0]
            mejor_x = pob[0].copy()

        # Guardar la información que necesita la animación
        historial_mejor_f.append(mejor_f)
        historial_mejor_x.append(mejor_x.copy())
        historial_poblacion.append(pob.copy())

    return {
        "mejor_x": mejor_x,
        "mejor_f": mejor_f,
        "evaluaciones": contador["evals"],
        "historial_mejor_f": historial_mejor_f,
        "historial_mejor_x": np.asarray(historial_mejor_x),
        "historial_poblacion": np.asarray(historial_poblacion)
    }


def evolucion_diferencial_gif(
    f_obj, dimension=2, lb=-5.0, ub=5.0,
    n_pop=40, max_generaciones=100,
    F=0.7, CR=0.8, semilla=None
):
    if semilla is not None:
        np.random.seed(semilla)

    lim_inf = np.full(dimension, lb) if np.isscalar(lb) else np.asarray(lb)
    lim_sup = np.full(dimension, ub) if np.isscalar(ub) else np.asarray(ub)

    contador = {"evals": 0}

    pob = np.random.uniform(
        lim_inf, lim_sup, size=(n_pop, dimension)
    )

    fitness = np.zeros(n_pop)
    for i in range(n_pop):
        fitness[i] = f_obj(pob[i])
        contador["evals"] += 1

    mejor_idx = np.argmin(fitness)
    mejor_x = pob[mejor_idx].copy()
    mejor_f = fitness[mejor_idx]

    historial_mejor_f = [mejor_f]
    historial_mejor_x = [mejor_x.copy()]
    historial_poblacion = [pob.copy()]

    for gen in range(1, max_generaciones + 1):
        nueva_pob = pob.copy()
        nuevo_fitness = fitness.copy()

        for i in range(n_pop):
            candidatos = [idx for idx in range(n_pop) if idx != i]
            r1, r2, r3 = np.random.choice(
                candidatos, size=3, replace=False
            )

            v_mutante = pob[r1] + F * (pob[r2] - pob[r3])
            v_mutante = np.clip(v_mutante, lim_inf, lim_sup)

            j_rand = np.random.randint(0, dimension)
            u_prueba = np.zeros(dimension)

            for j in range(dimension):
                if np.random.rand() < CR or j == j_rand:
                    u_prueba[j] = v_mutante[j]
                else:
                    u_prueba[j] = pob[i, j]

            f_prueba = f_obj(u_prueba)
            contador["evals"] += 1

            if f_prueba <= fitness[i]:
                nueva_pob[i] = u_prueba
                nuevo_fitness[i] = f_prueba

                if f_prueba < mejor_f:
                    mejor_f = f_prueba
                    mejor_x = u_prueba.copy()

        pob = nueva_pob
        fitness = nuevo_fitness

        # Guardar la información que necesita la animación
        historial_mejor_f.append(mejor_f)
        historial_mejor_x.append(mejor_x.copy())
        historial_poblacion.append(pob.copy())

    return {
        "mejor_x": mejor_x,
        "mejor_f": mejor_f,
        "evaluaciones": contador["evals"],
        "historial_mejor_f": historial_mejor_f,
        "historial_mejor_x": np.asarray(historial_mejor_x),
        "historial_poblacion": np.asarray(historial_poblacion)
    }

