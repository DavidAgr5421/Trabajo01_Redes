def resumir_de(grupo):
    valores = grupo["Valor_final"].to_numpy(dtype=float)
    valores_validos = valores[np.isfinite(valores)]

    if len(valores_validos) > 0:
        media = np.mean(valores_validos)
        desviacion = (
            np.std(valores_validos, ddof=1)
            if len(valores_validos) > 1
            else 0.0
        )
        mediana = np.median(valores_validos)
        mejor = np.min(valores_validos)
        peor = np.max(valores_validos)
    else:
        media = desviacion = mediana = mejor = peor = np.nan

    return pd.Series({
        "Corridas": len(grupo),
        "Media_valor_final": media,
        "Desviacion_estandar": desviacion,
        "Mediana_valor_final": mediana,
        "Mejor_resultado": mejor,
        "Peor_resultado": peor,
        "Tasa_exito_pct": 100 * grupo["Exito"].mean(),
        "Evaluaciones_funcion_promedio":
            grupo["Evaluaciones_funcion"].mean(),
        "Evaluaciones_gradiente_promedio":
            grupo["Evaluaciones_gradiente"].mean(),
        "Corridas_no_finitas":
            int((~np.isfinite(valores)).sum())
    })

