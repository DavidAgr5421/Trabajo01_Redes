def crear_gif_3d(nombre_funcion, algoritmo, fps=15):
    cfg = config_gif[nombre_funcion]
    funcion = cfg["funcion"]
    lb, ub = cfg["limites"]

    resultado = historiales_gif[nombre_funcion][algoritmo]

    # Recuperar las coordenadas del mejor punto
    if algoritmo in ["Descenso por gradiente", "PSO"]:
        trayectoria = np.asarray(resultado["historial_x"], dtype=float)
    else:
        trayectoria = np.asarray(
            resultado["historial_mejor_x"], dtype=float
        )

    # Recuperar la población cuando corresponda
    if algoritmo == "PSO":
        poblacion = np.asarray(
            resultado["historial_particulas"], dtype=float
        )
    elif algoritmo in ["Algoritmo evolutivo", "Evolución diferencial"]:
        poblacion = np.asarray(
            resultado["historial_poblacion"], dtype=float
        )
    else:
        poblacion = None

    validos = np.all(np.isfinite(trayectoria), axis=1)
    trayectoria = trayectoria[validos]

    if len(trayectoria) == 0:
        raise ValueError(
            f"No hay posiciones válidas para {nombre_funcion} - {algoritmo}"
        )

    # Reducir el número de fotogramas para que el GIF no sea tan pesado
    max_frames = 150
    indices = np.unique(
        np.linspace(
            0, len(trayectoria) - 1,
            min(max_frames, len(trayectoria))
        ).astype(int)
    )

    # Superficie 3D
    resolucion = 60
    x = np.linspace(lb, ub, resolucion)
    y = np.linspace(lb, ub, resolucion)
    X, Y = np.meshgrid(x, y)

    puntos_malla = np.column_stack([X.ravel(), Y.ravel()])
    Z = np.array([
    funcion(punto) for punto in puntos_malla]).reshape(X.shape)

    # Rosenbrock: transformación visual para apreciar el recorrido
    if nombre_funcion == "Rosenbrock":
        Z_plot = np.log10(1 + np.maximum(Z, 0))

        def transformar(valores):
            return np.log10(1 + np.maximum(valores, 0))

        etiqueta_z = "log10(1 + f(x))"
    else:
        Z_plot = Z

        def transformar(valores):
            return valores

        etiqueta_z = "f(x)"

    fig = plt.figure(figsize=(10, 7))
    ax = fig.add_subplot(111, projection="3d")

    ax.plot_surface(
        X, Y, Z_plot,
        cmap="viridis",
        alpha=0.65,
        linewidth=0,
        antialiased=True
    )

    ax.set_xlim(lb, ub)
    ax.set_ylim(lb, ub)
    ax.set_xlabel("x₁")
    ax.set_ylabel("x₂")
    ax.set_zlabel(etiqueta_z)
    ax.set_title(f"{nombre_funcion} — {algoritmo}")

    # Punto óptimo teórico
    z_optimo = transformar(np.array([0.0]))[0]
    ax.scatter(
        [0], [0], [z_optimo],
        color="red", marker="*", s=150,
        label="Óptimo global (0, 0)"
    )

    # Trayectoria del mejor punto
    linea, = ax.plot(
        [], [], [],
        color="black", linewidth=2,
        label="Mejor solución"
    )

    punto, = ax.plot(
        [], [], [],
        marker="o", color="red", markersize=7,
        linestyle="None"
    )

    texto = ax.text2D(
        0.03, 0.95, "",
        transform=ax.transAxes
    )

    # Población de partículas o individuos
    puntos_poblacion = None

    if poblacion is not None:
        puntos_poblacion = ax.scatter(
            [], [], [],
            color="deepskyblue",
            s=18,
            alpha=0.85,
            label="Población actual"
        )

    ax.legend(loc="upper right")

    def actualizar(frame):
        indice = indices[frame]

        recorrido = trayectoria[:indice + 1]
        valores = np.array([funcion(p) for p in recorrido])
        alturas = transformar(valores)

        linea.set_data_3d(
            recorrido[:, 0],
            recorrido[:, 1],
            alturas
        )

        punto.set_data_3d(
            [recorrido[-1, 0]],
            [recorrido[-1, 1]],
            [alturas[-1]]
        )

        texto.set_text(
            f"Paso: {indice}\nf(x) = {valores[-1]:.6g}"
        )

        if poblacion is not None:
            posiciones = poblacion[indice]
            posiciones = posiciones[
                np.all(np.isfinite(posiciones), axis=1)
            ]

            valores_p = np.array([
                funcion(p) for p in posiciones
            ])
            alturas_p = transformar(valores_p)

            puntos_poblacion._offsets3d = (
                posiciones[:, 0],
                posiciones[:, 1],
                alturas_p
            )

        return linea, punto, texto

    animacion = FuncAnimation(
        fig,
        actualizar,
        frames=len(indices),
        interval=1000 / fps,
        blit=False
    )

    nombre_archivo = (
        f"{nombre_funcion}_{algoritmo.replace(' ', '_')}_3D.gif"
    )
    ruta = CARPETA_GIFS / nombre_archivo

    animacion.save(
    str(ruta),
    writer=PillowWriter(fps=10))
    plt.close(fig)

    print(f"GIF creado: {nombre_archivo}")
    return ruta


