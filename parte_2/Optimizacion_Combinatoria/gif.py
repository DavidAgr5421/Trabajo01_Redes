def ejecutar_genetico():

    random.seed(SEMILLA)

    toolbox = base.Toolbox()

    toolbox.register(
        "indices",
        random.sample,
        range(N),
        N
    )

    toolbox.register(
        "individual",
        tools.initIterate,
        creator.IndividuoGIF,
        toolbox.indices
    )

    toolbox.register(
        "population",
        tools.initRepeat,
        list,
        toolbox.individual
    )

    toolbox.register(
        "evaluate",
        lambda individuo: (calcular_costo(individuo),)
    )

    toolbox.register(
        "mate",
        tools.cxOrdered
    )

    toolbox.register(
        "mutate",
        tools.mutShuffleIndexes,
        indpb=0.05
    )

    toolbox.register(
        "select",
        tools.selTournament,
        tournsize=3
    )

    # Crear población
    poblacion = toolbox.population(n=POBLACION)

    # Evaluar población inicial
    for individuo in poblacion:

        individuo.fitness.values = toolbox.evaluate(individuo)

    mejor = tools.selBest(poblacion, 1)[0]

    mejor_ruta = list(mejor)
    mejor_costo = float(mejor.fitness.values[0])

    historial = [
        (0, mejor_ruta.copy(), mejor_costo)
    ]

    # Guardaremos aproximadamente 70 momentos
    salto = max(1, GENERACIONES // 70)

    print("Ejecutando algoritmo genético...")

    for generacion in range(1, GENERACIONES + 1):

        # Selección
        padres = toolbox.select(
            poblacion,
            len(poblacion)
        )

        # Cruce y mutación
        descendientes = algorithms.varAnd(
            padres,
            toolbox,
            cxpb=PROB_CRUCE,
            mutpb=PROB_MUTACION
        )

        # Evaluar individuos modificados
        invalidos = [
            ind for ind in descendientes
            if not ind.fitness.valid
        ]

        for individuo in invalidos:

            individuo.fitness.values = toolbox.evaluate(
                individuo
            )

        poblacion = descendientes

        # Mejor individuo de esta generación
        actual = tools.selBest(poblacion, 1)[0]

        costo_actual = float(actual.fitness.values[0])

        # Guardar mejor solución encontrada hasta ahora
        if costo_actual < mejor_costo:

            mejor_costo = costo_actual
            mejor_ruta = list(actual)

        # Registrar momentos de la evolución
        if (
            generacion % salto == 0
            or generacion == GENERACIONES
        ):

            historial.append(
                (
                    generacion,
                    mejor_ruta.copy(),
                    mejor_costo
                )
            )

    print("Algoritmo genético finalizado")
    print(f"Mejor costo encontrado: €{mejor_costo:,.2f}")

    print(
        "Ruta:",
        " → ".join(ciudades[i] for i in mejor_ruta),
        "→",
        ciudades[mejor_ruta[0]]
    )

    return historial


historial_genetico = ejecutar_genetico()

# =============================================
# ALGORITMO COLONIA DE HORMIGAS
# IMPLEMENTACIÓN DE REFERENCIA
# =============================================

def ejecutar_aco(
    iteraciones=200,
    hormigas=47,
    alfa=1.0,
    beta=3.0,
    evaporacion=0.2,
    Q=1000.0
):

    rng = np.random.default_rng(SEMILLA)

    # Matriz de feromonas
    feromonas = np.ones((N, N))

    np.fill_diagonal(feromonas, 0)

    # Información heurística: inverso del costo
    visibilidad = np.zeros((N, N))

    np.divide(
        1.0,
        matriz_costos,
        out=visibilidad,
        where=matriz_costos > 0
    )

    mejor_ruta = None
    mejor_costo = np.inf

    historial = []

    print("Ejecutando colonia de hormigas...")

    for iteracion in range(1, iteraciones + 1):

        soluciones = []

        # Cada hormiga construye su recorrido
        for _ in range(hormigas):

            inicio = int(rng.integers(N))

            ruta = [inicio]

            disponibles = set(range(N))
            disponibles.remove(inicio)

            while disponibles:

                ciudad_actual = ruta[-1]

                opciones = np.array(
                    sorted(disponibles),
                    dtype=int
                )

                # Probabilidad de visitar cada ciudad
                pesos = (
                    feromonas[ciudad_actual, opciones] ** alfa
                    *
                    visibilidad[ciudad_actual, opciones] ** beta
                )

                if pesos.sum() > 0:

                    probabilidades = pesos / pesos.sum()

                else:

                    probabilidades = (
                        np.ones(len(opciones)) / len(opciones)
                    )

                siguiente = int(
                    rng.choice(
                        opciones,
                        p=probabilidades
                    )
                )

                ruta.append(siguiente)
                disponibles.remove(siguiente)

            costo = calcular_costo(ruta)

            soluciones.append(
                (costo, ruta.copy())
            )

            if costo < mejor_costo:

                mejor_costo = costo
                mejor_ruta = ruta.copy()

        # Evaporación de feromonas
        feromonas *= (1 - evaporacion)

        # Depositar feromonas en las mejores rutas
        soluciones.sort(key=lambda x: x[0])

        mejores_hormigas = soluciones[
            :max(1, hormigas // 5)
        ]

        for costo, ruta in mejores_hormigas:

            deposito = Q / costo

            for i in range(N):

                origen = ruta[i]
                destino = ruta[(i + 1) % N]

                feromonas[origen, destino] += deposito

        # Guardar mejor solución acumulada
        historial.append(
            (
                iteracion,
                mejor_ruta.copy(),
                float(mejor_costo)
            )
        )

    print("Colonia de hormigas finalizada")
    print(f"Mejor costo encontrado: €{mejor_costo:,.2f}")

    return historial


historial_aco = ejecutar_aco()

