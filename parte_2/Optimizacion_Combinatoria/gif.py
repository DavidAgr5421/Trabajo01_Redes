    # Seleccionar fotogramas del historial
    salto = max(
        1,
        len(historial) // cantidad_frames
    )

    seleccion = historial[::salto]

    if seleccion[-1][0] != historial[-1][0]:
        seleccion.append(historial[-1])

    # Datos del historial
    pasos = np.array([
        h[0] for h in historial
    ])

    costos = np.array([
        h[2] for h in historial
    ])

    # =========================================
    # CONFIGURACIÓN VISUAL
    # =========================================

